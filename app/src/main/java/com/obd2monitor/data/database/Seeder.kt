/**
 * Заполняет БД базовыми данными при первом запуске:
 *  - предустановленные профили автомобилей (ТЗ §11)
 *  - встроенный мини-справочник DTC (расширяется через assets/dtc_codes.csv)
 */
object Seeder {

    /** Устаревшие preset-id, оставшиеся в БД после рефакторинга списка пресетов.
     *  Чистим их при первом запуске новой версии — иначе у пользователя в Settings
     *  будут «висеть» Lada/VW/Renault/Kia, которых уже нет в коде. */
    private val obsoletePresetIds = listOf(
        "preset_lada_vesta_16",
        "preset_lada_vesta_18",
        "preset_lada_granta_16",
        "preset_lada_priora_16",
        "preset_renault_logan_16",
        "preset_vw_polo_sedan_16",
        "preset_kia_rio_15",
    )

    suspend fun seedIfEmpty(db: AppDatabase) {
        val vehicleDao = db.vehicleProfileDao()
        val presets = VehicleProfile.presets()

        // Удаляем устаревшие пресеты, если они есть в БД от предыдущей версии.
        // Если активным был один из них — очистим активный, чтобы перевыбрать дефолт.
        val active = vehicleDao.getActiveOnce()
        val activeWasObsolete = active != null && obsoletePresetIds.contains(active.id)
        obsoletePresetIds.forEach { id ->
            if (vehicleDao.getById(id) != null) vehicleDao.delete(id)
        }

        // Сидинг пресетов: только если запись с таким id ОТСУТСТВУЕТ в БД.
        //
        // НЕ делаем upsert поверх существующей записи на каждом запуске: иначе
        // затёрлись бы пользовательские поля (vin, licensePlate, отредактированные
        // вручную make/model/year/engineType и т.д.) — юзер открывает «Авто»,
        // правит поля, сохраняет, а preset из кода на следующем запуске перезаписал
        // бы всё назад, оставив пустой vin/plate.
        //
        // Решение: пресет — это СЕМЯ для свежей установки. После первого
        // upsert профиль становится «своим», и приложение не имеет права
        // перезаписывать его при обновлении кода. Если разработчик добавит
        // новые пресеты в `presets()` — они появятся (id новый, getById вернёт
        // null). Существующие — останутся какие есть.
        presets.forEach { p ->
            if (vehicleDao.getById(p.id) == null) {
                vehicleDao.upsert(p.toEntity(active = false))
            }
        }
        // Если активного нет (свежая установка либо был удалён obsolete) — активируем первый из списка.
        if (activeWasObsolete || vehicleDao.getActiveOnce() == null) {
            vehicleDao.setActive(presets.first().id)
        }

        val dtcDao = db.dtcCodeDao()
        // Перезаписываем встроенный каталог при каждом запуске — в новых версиях база
        // расширяется (200+ кодов), и мы хотим, чтобы пользовательские БД догоняли её
        // автоматически. INSERT OR REPLACE по primary key (code) обновит описания.
        dtcDao.insertAll(BuiltinDtcCatalog.minimal())
    }
}

