package com.obd2monitor.data.database

import com.obd2monitor.domain.model.DTCCode

/**
 * Справочник кодов неисправностей.
 *
 * Основа — стандартные коды SAE J2012 / ISO 15031-6 (P0xxx, P2xxx, P34xx–P39xx,
 * B0, C0, U0): у них одинаковый смысл на любом автомобиле с OBD-II/EOBD. Большая
 * часть таких кодов устроена семействами — датчик с пятью кодами «цепь / диапазон /
 * низкий / высокий / прерывистый», 12 цилиндров, катушки A–L, кислородные датчики
 * по банкам и т.д., — поэтому здесь они собираются по шаблонам, а не перечисляются
 * вручную. Поверх них ложатся описания из [BuiltinDtcCatalog] (написаны вручную,
 * точнее шаблонных) и дополнительные коды ниже.
 *
 * Коды производителя (P1xxx, P30–P33, B1/B2, C1/C2, U1/U2) у разных марок значат
 * разное: для них в описании прямо сказано, что расшифровка зависит от марки.
 */
object DtcLibrary {

    fun all(): List<DTCCodeEntity> {
        val map = LinkedHashMap<String, DTCCodeEntity>()
        generated().forEach { map[it.code] = it }
        BuiltinDtcCatalog.minimal().forEach { map[it.code] = it }
        extra().forEach { map[it.code] = it }
        return map.values.map(::markManufacturer)
    }

    /** Поясняем, что расшифровка кода производителя зависит от марки. */
    private fun markManufacturer(e: DTCCodeEntity): DTCCodeEntity {
        if (!DTCCode.isManufacturerSpecific(e.code) || e.description.startsWith(MANUFACTURER_PREFIX)) return e
        return e.copy(
            description = "$MANUFACTURER_PREFIX Типичная расшифровка: ${e.description}",
            recommendedActions = listOf(e.recommendedActions, "Сверить расшифровку с документацией вашей марки")
                .filter { it.isNotBlank() }.joinToString("; "),
        )
    }

    private const val MANUFACTURER_PREFIX = "Код производителя — значение зависит от марки."

    // ── Шаблоны ─────────────────────────────────────────────────────────────

    private fun code(n: Int) = "P%04d".format(n)

    private fun e(code: String, desc: String, causes: String, actions: String, critical: Boolean = false) =
        DTCCodeEntity(code, desc, causes, actions, critical)

