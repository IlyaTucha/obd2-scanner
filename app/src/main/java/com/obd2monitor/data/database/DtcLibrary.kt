    private const val CIRCUIT_ACTIONS = "Осмотреть разъём и проводку; Проверить питание (обычно 5 В) и массу датчика; Проверить сигнал датчика в live-данных"

    /**
     * Типовое семейство датчика: base — неисправность цепи, +1 — диапазон/характеристика,
     * +2 — низкий уровень сигнала, +3 — высокий, +4 — прерывистый сигнал.
     * [count] = 4, если пятый код в стандарте занят другим смыслом.
     */
    private fun sensorFamily(base: Int, name: String, critical: Boolean = false, count: Int = 5, rangeCauses: String? = null) = buildList {
        add(e(code(base), "$name — неисправность цепи", CIRCUIT_CAUSES, CIRCUIT_ACTIONS, critical))
        add(e(code(base + 1), "$name — выход за допустимый диапазон или неверная характеристика",
            rangeCauses ?: "Загрязнённый или изношенный датчик; Показания не согласуются с другими датчиками; Неисправность контролируемой системы",
            "Сравнить показания с фактическими условиями; Проверить связанную систему; Заменить датчик при подтверждении", critical))
        add(e(code(base + 2), "$name — низкий уровень сигнала",
            "Замыкание сигнального провода на массу; Нет питания датчика; Неисправный датчик",
            "Проверить питание и сигнальный провод; Проверить разъём; Заменить датчик при подтверждении", critical))
        add(e(code(base + 3), "$name — высокий уровень сигнала",
            "Замыкание сигнального провода на питание; Обрыв массы датчика; Неисправный датчик",
            "Проверить массу и сигнальный провод; Проверить разъём; Заменить датчик при подтверждении", critical))
        if (count >= 5) add(e(code(base + 4), "$name — прерывистый сигнал",
            "Плохой контакт в разъёме; Перетёртая проводка; Окисление клемм",
            "Осмотреть жгут в местах изгиба и креплений; Пошевелить проводку, наблюдая за сигналом в live-данных", critical))
    }

    /** Цепь управления исполнительным механизмом: base — цепь/обрыв, +1 — низкий, +2 — высокий. */
