package com.obd2monitor.domain.model

/**
 * Справочник параметров OBD2 для UI.
 *  - brief: 1 строка для краткой подсказки на карточке
 *  - detailed: многострочное объяснение под текущий профиль авто
 *  - normalRange: типичные значения для активного профиля
 *  - formula: откуда ECU берет это значение (для любопытных)
 */
data class MetricInfo(
    val title: String,
    val unit: String,
    val brief: String,
    val detailed: String,
    val normalRange: String,
    val formula: String? = null,
    val warning: String? = null,
)

/**
 * Короткие названия параметров — одни и те же на главной, в сессии, в итогах сессии
 * и на экране подробностей. Меняешь здесь — меняется везде.
 */
object MetricNames {
    private val names = mapOf(
        "speed" to "Скорость",
        "rpm" to "Обороты двигателя",
        "coolant" to "Температура антифриза",
        "battery" to "Напряжение бортсети",
        "load" to "Нагрузка двигателя",
        "throttle" to "Открытие дросселя",
        "warmup" to "Прогрев двигателя",
        "oil" to "Температура масла",
        "intake" to "Воздух на впуске",
        "timing" to "Угол зажигания",
        "ambient" to "Воздух за бортом",
        "fuelh" to "Расход сейчас",
        "fuel" to "Расход топлива",
        "fuellevel" to "Топливо в баке",
        "range" to "Запас хода",
        "stft" to "Краткая коррекция",
        "ltft" to "Долгая коррекция",
        "power" to "Мощность двигателя",
        "torque" to "Крутящий момент",
        "accel" to "Ускорение",
        "map" to "Давление во впуске",
        "vacuum" to "Вакуум во впуске",
        "maf" to "Расход воздуха",
        "distmil" to "Пробег с Check Engine",
        "distclear" to "Пробег после сброса",
        "stops" to "Остановки",
    )

    fun of(key: String): String = names[key] ?: key
    fun ofOrNull(key: String): String? = names[key]
}

object MetricCatalog {

    /** Атмосферный двигатель (без турбины) — определяется по описанию двигателя в профиле. */
    private fun isNaturallyAspirated(p: VehicleProfile?): Boolean {
        val e = p?.engineType?.lowercase() ?: return true
        return !e.contains("turbo") && !e.contains("tsi") && !e.contains("tfsi")
    }

    /** Подпись строки нормы: цифры в ней — для машины из профиля, поэтому называем её. */
    fun normLabel(profile: VehicleProfile?): String =
        profile?.name?.takeIf { it.isNotBlank() }?.let { "Норма для $it" } ?: "Норма"

    fun forKey(key: String, profile: VehicleProfile?): MetricInfo {
        val info = describe(key, profile)
        return MetricNames.ofOrNull(key)?.let { info.copy(title = it) } ?: info
    }

