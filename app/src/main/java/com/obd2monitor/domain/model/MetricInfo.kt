package com.obd2monitor.domain.model

/**
 * Справочник параметров OBD2 для UI.
 *  - brief: 1 строка для краткой подсказки на карточке
 *  - detailed: многострочное объяснение под текущий профиль авто
 *  - normalRange: типичные значения для активного профиля
 *  - formula: откуда ECU берет это значение (для любопытных)
 */
data class MetricInfo(
    val title: String,
    val unit: String,
    val brief: String,
    val detailed: String,
    val normalRange: String,
    val formula: String? = null,
    val warning: String? = null,
)

object MetricCatalog {

    /** Авто без турбины — большинство Accent/Lada/Logan. */
    private fun isNaturallyAspirated(p: VehicleProfile?): Boolean {
        val e = p?.engineType?.lowercase() ?: return true
        return !e.contains("turbo") && !e.contains("tsi") && !e.contains("tfsi")
    }

    private fun forCar(p: VehicleProfile?): String =
        p?.let { "для ${it.name}" } ?: "для текущей машины"

    fun forKey(key: String, profile: VehicleProfile?): MetricInfo {
        val car = forCar(profile)
        val na = isNaturallyAspirated(profile)
        val displ = profile?.displacementL ?: 1.5f
        val tank = profile?.tankCapacity ?: 45f

        return when (key) {

            "speed" -> MetricInfo(
                title = "Скорость",
                unit = "км/ч",
                brief = "Скорость машины по данным автомобиля.",
                detailed = "Это скорость, которую видит сама машина. Обычно она почти совпадает со спидометром и может немного отличаться от GPS.\n\n" +
                    "Если значение чуть выше GPS — это нормально: спидометры часто специально показывают немного больше реальной скорости.",
                normalRange = "Холостой ход 0 · Город 40–60 · Трасса 90–110",
                formula = "PID 01 0D: A (один байт = км/ч)",
            )

            "rpm" -> {
                val idle = profile?.idleRpm?.let { "${it.first}–${it.last}" } ?: "750–850"
                val max = profile?.normalRpm?.last ?: 6200
                val cruise = if (displ <= 1.4f) "2200–2700"
                else if (displ <= 1.6f) "1800–2400"
                else "1600–2200"
                MetricInfo(
                    title = "Обороты двигателя",
                    unit = "об/мин",
                    brief = "Скорость вращения коленвала.",
                    detailed = "Показывает, насколько быстро вращается двигатель. На холостом ходу обороты должны быть довольно ровными.\n\n" +
                        "Если обороты постоянно плавают, машина подёргивается или почти глохнет — стоит проверить дроссель, подсос воздуха, свечи и подачу топлива.\n\n" +
                        "На ровной дороге при спокойной езде двигатель ${displ}л обычно держится около $cruise об/мин. Если обороты слишком высокие — возможно, выбрана низкая передача.",
                    normalRange = "Холостой $idle · Крейсер $cruise · Максимум $max",
                    formula = "PID 01 0C: (256·A + B) / 4",
                )
            }

            "coolant" -> {
                val r = profile?.normalCoolantTempC?.let { "${it.first}–${it.last}" } ?: "85–95"
                MetricInfo(
                    title = "Температура антифриза",
                    unit = "°C",
                    brief = "Температура антифриза в системе охлаждения.",
                    detailed = "Это температура антифриза. После холодного запуска она должна плавно подняться до рабочей температуры.\n\n" +
                        "Если мотор долго не прогревается и держится около 60–70°C — возможна проблема с термостатом. Зимой из-за этого может плохо греть печка.\n\n" +
                        "Если температура растёт выше 105°C — это уже похоже на перегрев. Проверь уровень антифриза, вентилятор и радиатор.\n\n" +
                        "Норма $car: $r °C. Небольшие колебания при включении вентилятора — обычное дело.",
                    normalRange = r,
                    formula = "PID 01 05: A − 40",
                    warning = "> 105°C — срочно глушить и проверять систему охлаждения!",
                )
            }

            "intake" -> MetricInfo(
                title = "Темп. воздуха на впуске",
                unit = "°C",
                brief = "Температура воздуха перед дросселем.",
                detailed = "Показывает, насколько тёплый воздух попадает в двигатель. На стоянке воздух под капотом обычно теплее улицы, а на ходу температура должна снижаться.\n\n" +
                    "Если на ходу летом значение очень высокое, машина может тянуть хуже. Стоит проверить воздушный фильтр и приток холодного воздуха.",
                normalRange = "Лето 25–45 · Зима −10..+15 (по уличной)",
                formula = "PID 01 0F: A − 40",
            )

            "battery" -> {
                val r = profile?.normalBatteryV?.let { "%.1f–%.1f".format(it.start, it.endInclusive) } ?: "13.5–14.5"
                MetricInfo(
                    title = "Напряжение бортсети",
                    unit = "В",
                    brief = "Напряжение в электросети автомобиля.",
                    detailed = "Показывает напряжение в электросети автомобиля.\n\n" +
                        "С заглушенным двигателем это примерно заряд аккумулятора: около 12.6 В — хорошо, ниже 12.0 В — аккумулятор лучше зарядить.\n\n" +
                        "С заведённым двигателем напряжение должно быть выше, потому что работает генератор. Норма $car: $r В.\n\n" +
                        "Если при работающем двигателе меньше 13 В — генератор может плохо заряжать. Если выше 15 В — возможна неисправность регулятора напряжения.",
                    normalRange = "Двигатель не работает 12.4–12.8 · Работает $r",
                    formula = "PID 01 42: (256·A + B) / 1000",
                    warning = "< 12.0 В при работе — диагностика генератора. > 15.0 В — реле-регулятор.",
                )
            }

            "throttle" -> MetricInfo(
                title = "Положение дросселя",
                unit = "%",
                brief = "Насколько открыта дроссельная заслонка.",
                detailed = "Показывает, насколько открыт дроссель — грубо говоря, насколько двигатель «просит воздуха».\n\n" +
                    "На холостом ходу значение не обязано быть нулём: заслонка обычно немного приоткрыта, чтобы двигатель не заглох.\n\n" +
                    "Если на холостом значение слишком высокое или обороты плавают — возможно, дроссель загрязнён или есть подсос воздуха.",
                normalRange = "Холостой 12–18 · Крейсер 18–30 · Полный газ 80–100",
                formula = "PID 01 11: A · 100 / 255",
            )

            "load" -> MetricInfo(
                title = "Нагрузка двигателя",
                unit = "%",
                brief = "Процент использования потенциала двигателя сейчас.",
                detailed = "Показывает, насколько тяжело сейчас работает двигатель.\n\n" +
                    "Низкая нагрузка — спокойная езда или холостой ход. Высокая нагрузка — разгон, подъём в гору, полный газ или слишком высокая передача для текущей скорости.\n\n" +
                    "$car: на ровной дороге при спокойной езде обычно 25–40%. Если постоянно выше 50% без причины — проверь воздушный фильтр, давление в шинах, тормоза и выбранную передачу.",
                normalRange = "Холостой 15–25 · Крейсер 25–40 · Разгон 70–100",
                formula = "PID 01 04: A · 100 / 255",
            )

            "fuelh" -> MetricInfo(
                title = "Расход в час",
                unit = "л/ч",
                brief = "Сколько литров/час сжигает двигатель сейчас.",
                detailed = "Мгновенный расход в литрах в час. Имеет смысл при ЛЮБОЙ скорости, " +
                    "включая стоянку — поэтому в пробках смотри на эту цифру, а не на л/100км.\n\n" +
                    "Холостой ход (двигатель работает, машина стоит) для $car: 0.6–1.5 л/ч (зависит " +
                    "от прогрева, кондиционера и нагрузки на генератор). Накат с горки: 0 (cut-off, " +
                    "форсунки отключены). Полный газ: 15–25 л/ч.\n\n" +
                    "Парная карточка «Расход» показывает то же самое в л/100км — но та цифра " +
                    "теряет смысл при околонулевой скорости (делитель → 0).",
                normalRange = "Холостой 0.6–1.5 · Крейсер 4–7 · Полный газ 15–25",
                formula = "MAF × 3600 / (AFR × ρ_бензина) или PID 5E напрямую",
            )

            "fuel" -> {
                // Hyundai Accent / Kia Rio 1.4-1.6: город ~7-10, трасса ~5-7
                val cityRange = when {
                    displ <= 1.3f -> "6–9"
                    displ <= 1.6f -> "7–10"
                    displ <= 1.8f -> "8–11"
                    else -> "9–13"
                }
                val highway = when {
                    displ <= 1.3f -> "4–6"
                    displ <= 1.6f -> "5–7"
                    displ <= 1.8f -> "6–8"
                    else -> "7–9"
                }
                val jam = when {
                    displ <= 1.6f -> "10–16"
                    else -> "13–20"
                }
                MetricInfo(
                    title = "Расход топлива",
                    unit = "л/100км",
                    brief = "Сколько литров уйдёт на 100 км при текущих условиях.",
                    detailed = "Показывает, сколько топлива машина тратит в текущих условиях, в привычных литрах на 100 км.\n\n" +
                        "На разгоне и в пробках расход обычно высокий. На ровной трассе при спокойной скорости — заметно ниже. При движении накатом на передаче расход может падать почти до нуля — это нормально.\n\n" +
                        "Норма $car (объём ${displ}л, бак ${tank.toInt()}л): город $cityRange · трасса $highway · пробки $jam.\n\n" +
                        "Если расход стал заметно выше обычного, проверь давление в шинах, воздушный фильтр, свечи, тормоза и качество топлива.",
                    normalRange = "Город $cityRange · Трасса $highway · Пробки $jam",
                    formula = "MAF / 14.7 · ρ_топлива · 100 / скорость · 3600 (или из MAP+RPM)",
                )
            }

            "map" -> {
                // NA двигатели: на холостом большой вакуум, при WOT почти атмосфера
                val wot = if (na) "85–100" else "100–250 (с турбонаддувом)"
                MetricInfo(
                    title = "Давление впуска",
                    unit = "кПа",
                    brief = "Сколько воздуха двигатель получает через впуск.",
                    detailed = "Этот показатель помогает понять, насколько свободно двигатель дышит.\n\n" +
                        "На холостом ходу давление обычно низкое, потому что дроссель почти закрыт. При нажатии газа давление растёт.\n\n" +
                        "При полном газе $car обычно показывает около $wot кПа. Если на холостом значение слишком высокое — возможен подсос воздуха или проблема с дросселем.",
                    normalRange = "Холостой 30–45 · Крейсер 45–70 · Полный газ $wot",
                    formula = "PID 01 0B: A (кПа)",
                )
            }

            "timing" -> MetricInfo(
                title = "Угол опережения зажигания",
                unit = "°",
                brief = "Насколько рано срабатывает свеча зажигания.",
                detailed = "Показывает, в какой момент зажигается смесь в цилиндре. Машина постоянно подбирает этот момент сама.\n\n" +
                    "Обычно значение положительное. При разгоне, высокой нагрузке или плохом бензине оно может уменьшаться.\n\n" +
                    "Если угол часто уходит в минус или машина звенит/тупит под нагрузкой — попробуй сменить АЗС и проверь свечи.",
                normalRange = "Холостой +5..+15 · Крейсер +20..+35 · Под нагрузкой может уходить в минус",
                formula = "PID 01 0E: A / 2 − 64",
            )

            "oil" -> MetricInfo(
                title = "Температура масла",
                unit = "°C",
                brief = "Температура моторного масла.",
                detailed = "Масло прогревается медленнее антифриза. Даже если температура двигателя уже нормальная, масло ещё может быть холодным.\n\n" +
                    "Пока масло не прогрелось примерно до 80°C, лучше ехать спокойно и не давить газ в пол.\n\n" +
                    "$car: рабочая температура обычно 90–110°C. Если масло приближается к 130°C — это повод снизить нагрузку и проверить систему охлаждения.",
                normalRange = "Прогретый 90–110 · Под нагрузкой до 120",
                formula = "PID 01 5C: A − 40",
            )

            "stft" -> MetricInfo(
                title = "Краткая коррекция топлива",
                unit = "%",
                brief = "Быстрая поправка подачи топлива прямо сейчас.",
                detailed = "Показывает, как машина прямо сейчас подстраивает подачу топлива.\n\n" +
                    "Плюс означает: машина добавляет топлива. Минус означает: машина убавляет топлива.\n\n" +
                    "Небольшие колебания около нуля — нормально. Если значение долго держится выше +10% или ниже −10%, стоит проверить подсос воздуха, форсунки, бензонасос и датчик кислорода.",
                normalRange = "−5..+5 (норма) · ±10 (повод проверить)",
                formula = "PID 01 06: (A − 128) · 100 / 128",
            )

            "ltft" -> MetricInfo(
                title = "Долгая коррекция топлива",
                unit = "%",
                brief = "Долгая привычная поправка подачи топлива.",
                detailed = "Показывает, к какой поправке топлива машина привыкла за последние поездки.\n\n" +
                    "Если значение близко к нулю — всё хорошо. Большой плюс значит, что машина постоянно добавляет топливо. Большой минус — постоянно убавляет.\n\n" +
                    "$car: норма около ±5%. Если держится за ±15%, стоит искать причину: подсос воздуха, грязный датчик воздуха, форсунки, насос или давление топлива.",
                normalRange = "−5..+5 (норма) · ±15 (диагностика)",
                formula = "PID 01 07: (A − 128) · 100 / 128",
            )

            "distmil" -> MetricInfo(
                title = "Пробег с горящим Check Engine",
                unit = "км",
                brief = "Сколько км машина проехала с включенной лампой неисправности.",
                detailed = "Если лампочка Check Engine не горит — обычно здесь будет 0. Если горит — показатель показывает, сколько километров машина уже проехала с ошибкой.\n\n" +
                    "Чем дольше ездить с активной ошибкой, тем выше риск повредить катализатор, датчики или другие узлы. Лучше не откладывать диагностику.",
                normalRange = "0 (если лампы нет)",
                formula = "PID 01 21: 256·A + B",
            )

            "distclear" -> MetricInfo(
                title = "Пробег после сброса ошибок",
                unit = "км",
                brief = "Сколько проехала машина с момента последнего сброса ошибок.",
                detailed = "Показывает, сколько машина проехала после последнего сброса ошибок.\n\n" +
                    "Это удобно после ремонта: сбросил ошибки, поездил несколько дней и смотришь, вернулась проблема или нет. Если ошибки снова появились — ремонт не решил причину.",
                normalRange = "Растет с каждым километром",
                formula = "PID 01 31: 256·A + B",
            )

            "fuellevel" -> MetricInfo(
                title = "Уровень топлива",
                unit = "%",
                brief = "Оценка остатка топлива по датчику в баке.",
                detailed = "Показывает примерный остаток топлива в баке в процентах.\n\n" +
                    "На уклонах, после резкого торможения или сразу после заправки значение может меняться не сразу — это нормально. Для запаса хода приложение использует этот процент, объём бака из профиля и средний расход.",
                normalRange = "0–100",
                formula = "PID 01 2F: A × 100 / 255",
            )

            "maf" -> MetricInfo(
                title = "Расход воздуха",
                unit = "г/с",
                brief = "Сколько воздуха проходит через двигатель.",
                detailed = "Двигателю нужен воздух для сгорания топлива. Этот показатель показывает, сколько воздуха сейчас проходит через впуск.\n\n" +
                    "На холостом ходу у небольших бензиновых моторов обычно 2–4 г/с. Если значение явно странное, машина может тянуть хуже или расходовать больше топлива.",
                normalRange = "Холостой 2–4 · На разгоне растёт вместе с оборотами",
                formula = "PID 01 10: (256·A + B) / 100",
            )

            "ambient" -> MetricInfo(
                title = "Температура за бортом",
                unit = "°C",
                brief = "Температура воздуха снаружи автомобиля.",
                detailed = "Показывает температуру за бортом, если машина отдаёт такие данные.\n\n" +
                    "На старых автомобилях этот показатель может отсутствовать — тогда карточка просто не появится.",
                normalRange = "Зависит от погоды",
                formula = "PID 01 46: A − 40",
            )

            "power" -> {
                val maxKw = profile?.maxPowerKw ?: 70
                val maxHp = (maxKw * 1.36f).toInt()
                MetricInfo(
                    title = "Мощность",
                    unit = "л.с.",
                    brief = "Сколько лошадиных сил сейчас выдаёт двигатель.",
                    detailed = "Показывает примерную мощность, которую двигатель выдаёт прямо сейчас.\n\n" +
                        "На холостом ходу мощность маленькая. При спокойной езде по трассе нужна только часть мощности. При разгоне, подъёме в гору или полном газе значение растёт.\n\n" +
                        "$car: паспортный максимум примерно $maxHp л.с. В приложении это расчётная оценка, поэтому она может немного отличаться от стенда.",
                    normalRange = "Холостой 1–4 л.с. · Крейсер 16–25 л.с. · Разгон до $maxHp л.с.",
                    formula = "(MAF × 0.88 или load% × maxTorqueNm × RPM / 9549) × 1.35962",
                )
            }

            "torque" -> {
                val maxTq = profile?.maxTorqueNm ?: 130
                MetricInfo(
                    title = "Крутящий момент",
                    unit = "Нм",
                    brief = "Усилие на коленвале сейчас.",
                    detailed = "Это тяга двигателя в текущий момент. Чем выше момент, тем легче машине разгоняться или ехать в гору.\n\n" +
                        "$car: максимум примерно $maxTq Нм. На слишком низких оборотах тяги обычно меньше, поэтому иногда лучше переключиться на передачу ниже, чем давить газ на высокой.",
                    normalRange = "Холостой 5–15 · Крейсер 30–60 · Полный газ до $maxTq",
                    formula = "Power(кВт) × 9549 / RPM",
                )
            }

            "vacuum" -> MetricInfo(
                title = "Вакуум во впуске",
                unit = "кПа",
                brief = "Разрежение между атмосферой и впускным коллектором.",
                detailed = "Показывает разрежение во впуске. Проще говоря, насколько сильно двигатель «тянет» воздух через дроссель.\n\n" +
                    "На холостом ходу вакуум обычно высокий. При нажатии газа вакуум падает. При полном газе он почти исчезает.\n\n" +
                    "Если на холостом вакуум заметно ниже обычного — возможен подсос воздуха или проблема с дросселем.",
                normalRange = "Холостой 60–70 · Крейсер 30–50 · Полный газ 0–5",
                formula = "101 кПа − MAP",
            )

            "warmup" -> {
                val target = profile?.normalCoolantTempC?.first ?: 85
                MetricInfo(
                    title = "Прогрев двигателя",
                    unit = "%",
                    brief = "Дошёл ли двигатель до рабочей температуры.",
                    detailed = "Показывает, насколько двигатель приблизился к рабочей температуре.\n\n" +
