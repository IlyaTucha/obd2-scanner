                    brief = "Мгновенный расход в литрах на 100 км: сколько топлива уйдёт, если ехать так же, как сейчас.",
                    detailed = "Значение сильно скачет: на разгоне и в пробке оно высокое, на ровной трассе низкое. Средний расход за поездку показан в итогах сессии.\n\n" +
